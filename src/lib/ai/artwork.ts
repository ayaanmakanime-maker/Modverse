/**
 * Layer 2 — artwork generation / retrieval.
 *
 * Turns the Director's artwork requests into USABLE assets (never just
 * descriptions): Creative Library graphics, or — only when an image model is
 * configured and the request allows it — newly generated images stored
 * privately as uploads. Every result carries an asset reference, dimensions,
 * format, transparency, licensing and print-compatibility metadata. A
 * generated image is never claimed when none was produced.
 */
import type { LibraryLookup } from "../library/lookup";
import type { ResolvedAsset } from "../garment/operations";
import type { ArtworkRequest } from "./proposal";

export interface ResolvedArtwork {
  ref: string;
  status: "resolved" | "unresolved";
  source?: "library" | "generated" | "upload";
  assetId?: string;
  name?: string;
  url?: string;
  width?: number;
  height?: number;
  format?: "vector" | "raster";
  transparent?: boolean;
  license?: string;
  collection?: string;
  /** Vector artwork scales freely; rasters list the widest print at 150 DPI. */
  printability?: { vector: boolean; maxWidthCmAt150dpi: number | null };
  note?: string;
}

export interface GeneratedImage {
  provider: string;
  image: { id: string; url: string; width: number | null; height: number | null; name: string | null; mime: string };
}

export interface ArtworkDeps {
  lib: LibraryLookup;
  /** Present only when an image provider is active AND the user may store uploads. */
  generate?: (prompt: string) => Promise<GeneratedImage>;
}

const STICKER = /\b(sticker|badge|emblem|patch|logo|icon|mark)\b/i;

function fromLibrary(req: ArtworkRequest, lib: LibraryLookup): ResolvedArtwork | null {
  let asset = req.assetId ? lib.get(req.assetId) : undefined;
  if (!asset) {
    const text = `${req.description} ${(req.collections ?? []).join(" ")}`;
    const cols = [...(req.collections ?? []).filter((c) => lib.search({ collections: [c], limit: 1 }).total > 0), ...lib.matchCollections(text).map((c) => c.slug)];
    const kind = STICKER.test(req.description) ? "element" : "graphic";
    const words = req.description.toLowerCase().split(/\W+/).filter((w) => w.length > 3);
    asset = lib.pick(kind, cols.slice(0, 2), text, words) ?? lib.pick("graphic", cols.slice(0, 2), text, words);
    if (!asset || (!cols.length && !words.some((w) => asset!.name.toLowerCase().includes(w)))) {
      // No stylistic match: only accept a generic pick when the request did not ask for something specific.
      if (!asset || words.length > 2) return null;
    }
  }
  if (!asset?.url || (asset.kind !== "graphic" && asset.kind !== "element" && asset.kind !== "template")) return null;
  return {
    ref: req.ref,
    status: "resolved",
    source: "library",
    assetId: asset.id,
    name: asset.name,
    url: asset.kind === "template" ? (asset.baseUrl ?? asset.url) : asset.url,
    width: asset.width,
    height: asset.height,
    format: "vector",
    transparent: true,
    license: asset.license ?? "ModVerse Original Creative Library v0.1",
    collection: asset.collectionName,
    printability: { vector: true, maxWidthCmAt150dpi: null },
  };
}

export async function resolveArtwork(requests: ArtworkRequest[], deps: ArtworkDeps): Promise<ResolvedArtwork[]> {
  const out: ResolvedArtwork[] = [];
  for (const req of requests) {
    const wantsGeneration = req.source === "generate";
    if (wantsGeneration && deps.generate) {
      try {
        const g = await deps.generate(`${req.description}${req.colors?.length ? `, colour palette ${req.colors.join(" ")}` : ""}`);
        const w = g.image.width ?? 1024;
        const h = g.image.height ?? 1024;
        const vector = g.image.mime === "image/svg+xml";
        out.push({
          ref: req.ref, status: "resolved", source: "generated", assetId: g.image.id, name: g.image.name ?? "Generated artwork", url: g.image.url, width: w, height: h,
          format: vector ? "vector" : "raster", transparent: vector || g.image.mime === "image/png",
          license: `Generated with ${g.provider} — check the model's commercial-use terms before production`,
          printability: { vector, maxWidthCmAt150dpi: vector ? null : +((w / 150) * 2.54).toFixed(1) },
          note: `Generated by ${g.provider}`,
        });
        continue;
      } catch (e) {
        const lib = fromLibrary(req, deps.lib);
        out.push(lib ? { ...lib, note: `Image generation failed (${e instanceof Error ? e.message : "error"}) — used library artwork instead` } : { ref: req.ref, status: "unresolved", note: `Image generation failed: ${e instanceof Error ? e.message : "error"}` });
        continue;
      }
    }
    const lib = fromLibrary(req, deps.lib);
    if (lib) out.push(wantsGeneration ? { ...lib, note: "No image-generation model is configured — matched Creative Library artwork instead (nothing was generated)" } : lib);
    else out.push({ ref: req.ref, status: "unresolved", note: wantsGeneration ? "No image-generation model is configured and no library artwork matched" : `No Creative Library artwork matched "${req.description.slice(0, 60)}"` });
  }
  return out;
}

export function artworkAssets(resolved: ResolvedArtwork[]): Record<string, ResolvedAsset> {
  const assets: Record<string, ResolvedAsset> = {};
  for (const r of resolved) if (r.status === "resolved" && r.assetId && r.url) assets[r.assetId] = { id: r.assetId, name: r.name ?? r.assetId, url: r.url, width: r.width ?? 100, height: r.height ?? 100, source: r.source };
  return assets;
}
