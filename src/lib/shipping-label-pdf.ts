import "server-only";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

export interface LabelInput {
  awb: string;
  courier: string;
  orderNumber: string;
  direction: "forward" | "return";
  weightGrams: number;
  units: number;
  cod: number | null;
  to: Record<string, string>;
  from: { name: string; city?: string | null; state?: string | null };
  partner: string;
}

const clean = (v: unknown) => String(v ?? "").replace(/[^\x20-\x7E]/g, "?");

/** 4x6in thermal-style label. The barcode is a readable Code-39-like stripe pattern for demos, not a carrier-certified barcode. */
export async function renderShippingLabel(l: LabelInput): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`Shipping label ${l.awb}`);
  doc.setCreator("ModVerse logistics portal");
  const page = doc.addPage([288, 432]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.05, 0.05, 0.05);
  let y = 410;
  const text = (s: string, size = 9, f = font, x = 14) => { page.drawText(clean(s), { x, y, size, font: f, color: ink }); y -= size + 4; };
  page.drawRectangle({ x: 8, y: 8, width: 272, height: 416, borderColor: ink, borderWidth: 1.2 });
  text(`${l.courier.toUpperCase()}  ·  ${l.direction === "return" ? "RETURN" : "FORWARD"}${l.cod !== null ? "  ·  COD" : "  ·  PREPAID"}`, 11, bold);
  text(`AWB ${l.awb}`, 16, bold);
  // Stripe pattern derived from the AWB characters (visual only).
  let x = 14;
  for (const ch of l.awb) {
    const c = ch.charCodeAt(0);
    for (let b = 0; b < 6; b++) {
      const w = (c >> b) & 1 ? 2.4 : 1.1;
      page.drawRectangle({ x, y: y - 40, width: w, height: 40, color: ink });
      x += w + 1.3;
      if (x > 268) break;
    }
  }
  y -= 52;
  page.drawLine({ start: { x: 8, y }, end: { x: 280, y }, thickness: 1, color: ink });
  y -= 14;
  text("DELIVER TO", 8, bold);
  text(l.to.name ?? "", 12, bold);
  for (const line of [l.to.line1, l.to.line2, `${l.to.city ?? ""}, ${l.to.state ?? ""}`, `PIN ${l.to.pincode ?? ""}`, `Phone ${l.to.phone ?? ""}`]) if (line && line.trim() && line.trim() !== ",") text(line, 10);
  y -= 4;
  page.drawLine({ start: { x: 8, y }, end: { x: 280, y }, thickness: 1, color: ink });
  y -= 14;
  text("FROM", 8, bold);
  text(l.from.name, 10, bold);
  if (l.from.city || l.from.state) text([l.from.city, l.from.state].filter(Boolean).join(", "), 9);
  y -= 4;
  page.drawLine({ start: { x: 8, y }, end: { x: 280, y }, thickness: 1, color: ink });
  y -= 14;
  text(`Order ${l.orderNumber}   ·   ${l.units} unit(s)   ·   ${(l.weightGrams / 1000).toFixed(2)} kg`, 9);
  if (l.cod !== null) text(`COLLECT ON DELIVERY: INR ${l.cod}`, 12, bold);
  text(`Handled by ${l.partner}`, 8);
  y = 22;
  text("Generated by ModVerse (simulated courier integration - not a carrier-issued label)", 6.5);
  return doc.save();
}
