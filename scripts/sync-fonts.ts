/**
 * Copies the OFL-licensed font files used by the ModVerse typography editor
 * from the @fontsource packages into public/fonts and generates
 * public/fonts/fonts.css (with accurate unicode-range per subset, parsed from
 * the Fontsource CSS) plus each family's OFL licence text.
 *
 * Usage: npm run fonts:sync
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { FONTS } from "../src/lib/typography/fonts";

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "public/fonts");

function main() {
  mkdirSync(OUT, { recursive: true });
  const css: string[] = ["/* Generated by scripts/sync-fonts.ts — OFL-1.1 fonts served locally. */"];
  let files = 0;
  const missing: string[] = [];
  for (const f of FONTS) {
    const pkgDir = path.join(ROOT, "node_modules/@fontsource", f.pkg);
    if (!existsSync(pkgDir)) {
      missing.push(`package @fontsource/${f.pkg}`);
      continue;
    }
    const famOut = path.join(OUT, f.pkg);
    mkdirSync(famOut, { recursive: true });
    const lic = ["LICENSE", "LICENSE.md", "OFL.txt"].map((n) => path.join(pkgDir, n)).find(existsSync);
    if (lic) copyFileSync(lic, path.join(famOut, "LICENSE.txt"));
    const variants: [number, boolean][] = [...f.weights.map((w) => [w, false] as [number, boolean]), ...f.italic.map((w) => [w, true] as [number, boolean])];
    for (const [weight, italic] of variants) {
      const cssFile = path.join(pkgDir, italic ? `${weight}-italic.css` : `${weight}.css`);
      if (!existsSync(cssFile)) {
        missing.push(`${f.family} ${weight}${italic ? " italic" : ""} css`);
        continue;
      }
      const blocks = readFileSync(cssFile, "utf8").match(/\/\*[^*]*\*\/\s*@font-face\s*{[^}]*}/g) ?? [];
      for (const block of blocks) {
        const subset = new RegExp(`/\\*\\s*${f.pkg}-(.+?)-\\d+-(?:normal|italic)\\s*\\*/`).exec(block)?.[1];
        if (!subset || !f.subsets.includes(subset)) continue;
        const fileName = `${f.pkg}-${subset}-${weight}-${italic ? "italic" : "normal"}.woff2`;
        const src = path.join(pkgDir, "files", fileName);
        if (!existsSync(src)) {
          missing.push(fileName);
          continue;
        }
        copyFileSync(src, path.join(famOut, fileName));
        files++;
        const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
        css.push(
          `@font-face{font-family:'${f.family}';font-style:${italic ? "italic" : "normal"};font-display:swap;font-weight:${weight};src:url(/fonts/${f.pkg}/${fileName}) format('woff2');${range ? `unicode-range:${range};` : ""}}`,
        );
      }
    }
  }
  writeFileSync(path.join(OUT, "fonts.css"), css.join("\n") + "\n");
  console.log(`Synced ${files} font files for ${FONTS.length} families → public/fonts`);
  if (missing.length) {
    console.error(`Missing:\n - ${missing.join("\n - ")}`);
    process.exitCode = 1;
  }
}

main();
